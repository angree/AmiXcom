#!/usr/bin/env python3
"""Loading-splash assets, embedded in the executable (AMIGA-PORT).

Converts the PNGs in intro/ and emits a C file with the data linked straight
into the binary (no data files on disk). native/amiga_splash.c parses these
blobs; they use the same byte layout a file would.

Palette layout (one 256-entry palette per background):
  0        black - FIXED (screen border and bar text pen)
  1        yellow - FIXED (screen title-bar background, like the game's)
  2        white - FIXED (title-bar gadget)
  3        black - FIXED
  4..228   background colours (quantised per image)
  230..252 logo colours (shared across all backgrounds)
  253      progress-bar fill - FIXED muted steel blue
  254      black (bar background / bottom band)
  255      transparent marker in the logo data (never displayed)

Blob layout (big-endian):
  bg  : 'SPL1' u16 w u16 h  palette[256*3]  pixels[w*h]
  logo: 'SPLG' u16 w u16 h  pixels[w*h]     (255 = transparent)
"""
import glob, os, struct, sys
from PIL import Image

# Intuition pens on our screen (see g_screen_pens in native/amiga_gfx.c):
#   0 = trim/border, 15 = bar TEXT, 17 = bar BACKGROUND, 19 = gadget fill
PEN_TRIM = (0, 0, 0)
PEN_TEXT = (0, 0, 0)            # black text on the yellow bar
PEN_BAR  = (232, 216, 64)       # game-like yellow title bar
PEN_FILL = (108, 116, 132)      # gadget
BAR_FILL = (108, 160, 176)      # loading-bar fill, always the same
BLACK = (0, 0, 0)
RESERVED = (0, 15, 17, 19)
ALLOWED = [i for i in range(1, 230) if i not in RESERVED]

def quant_logo(path):
    im = Image.open(path).convert("RGBA")
    bbox = im.split()[3].getbbox()      # trim transparent padding
    if bbox:
        im = im.crop(bbox)
    rgb = im.convert("RGB")
    q = rgb.quantize(colors=23, method=Image.MEDIANCUT)
    pal = q.getpalette()[: 23 * 3]
    px = q.load()
    a = im.split()[3].load()
    data = bytearray()
    for y in range(im.height):
        for x in range(im.width):
            data.append(255 if a[x, y] <= 128 else 230 + px[x, y])
    return im.width, im.height, pal, bytes(data)

def c_array(name, blob):
    out = ["static const unsigned char %s[] = {" % name]
    for i in range(0, len(blob), 24):
        out.append(",".join(str(b) for b in blob[i:i + 24]) + ",")
    out.append("};")
    return "\n".join(out)

def main(intro_dir, out_c):
    lw, lh, logo_pal, logo_px = quant_logo(os.path.join(intro_dir, "small_amixcom_logo.png"))
    logo_blob = b"SPLG" + struct.pack(">HH", lw, lh) + logo_px

    bg_blobs = []
    bgs = sorted(g for g in glob.glob(os.path.join(intro_dir, "*.png"))
                 if "logo" not in os.path.basename(g).lower())
    for path in bgs:
        im = Image.open(path).convert("RGB")
        ncol = len(ALLOWED)
        # NOTE: no dithered remap - tried Floyd-Steinberg here, the user
        # found the grain ugly at 320x200; smooth banding won.
        q = im.quantize(colors=ncol, method=Image.MEDIANCUT)
        bpal = q.getpalette()[: ncol * 3]
        pal = bytearray(768)
        pal[0:3] = bytes(PEN_TRIM)
        pal[15 * 3: 15 * 3 + 3] = bytes(PEN_TEXT)
        pal[17 * 3: 17 * 3 + 3] = bytes(PEN_BAR)
        pal[19 * 3: 19 * 3 + 3] = bytes(PEN_FILL)
        for k in range(ncol):
            pal[ALLOWED[k] * 3: ALLOWED[k] * 3 + 3] = bpal[k * 3: k * 3 + 3]
        pal[230 * 3: 230 * 3 + len(logo_pal)] = logo_pal
        pal[253 * 3: 253 * 3 + 3] = bytes(BAR_FILL)
        pal[254 * 3: 254 * 3 + 3] = bytes(BLACK)
        pal[255 * 3: 255 * 3 + 3] = bytes(BLACK)
        remap = bytes(ALLOWED[b] if b < ncol else 254 for b in range(256))
        px = bytes(remap[b] for b in q.tobytes())
        bg_blobs.append(b"SPL1" + struct.pack(">HH", im.width, im.height) + bytes(pal) + px)

    parts = ["/* generated by build/gen_splash.py from intro/ - do not edit */\n"]
    for n, blob in enumerate(bg_blobs):
        parts.append(c_array("splash_bg%d" % n, blob))
    parts.append(c_array("splash_logo", logo_blob))
    parts.append("const int AmigaSplashBgCount = %d;" % len(bg_blobs))
    parts.append("const unsigned char * const AmigaSplashBgs[] = { %s };"
                 % ", ".join("splash_bg%d" % n for n in range(len(bg_blobs))))
    parts.append("const unsigned char * const AmigaSplashLogo = splash_logo;")
    with open(out_c, "w") as f:
        f.write("\n".join(parts) + "\n")
    print("splash: %d backgrounds + logo -> %s (%d KB)"
          % (len(bg_blobs), out_c, sum(len(b) for b in bg_blobs) // 1024))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
